// The server's own data — sessions and calendar-feed tokens — are classes
// of the model like any other, so they go through the data view layer and
// the routing, replicate with everything else, and need no SQL of their
// own. They are added to every app's model; the API and the pages don't
// show them (frameworkClass).
const frameworkModel = `
classes:
  FrameworkSession:
    label: Session
    table: dd_sessions
    access: {owner: principal_id, read: owner, write: nobody}
    slots:
      - {name: id, type: integer, autogenerated: true, read_only: true}
      - {name: token_hash, type: string, required: true, max: 64}
      - {name: principal_id, type: integer, required: true}
      - {name: expires_at, type: datetime, required: true}
      - {name: created_at, type: datetime, autogenerated: true}
    constraints:
      unique: [token_hash]
  FrameworkFeed:
    label: Calendar feed
    table: dd_feeds
    access: {owner: principal_id, read: owner, write: nobody}
    slots:
      - {name: id, type: integer, autogenerated: true, read_only: true}
      - {name: principal_id, type: integer, required: true}
      - {name: token, type: string, required: true, max: 64}
      - {name: created_at, type: datetime, autogenerated: true}
    constraints:
      unique: [principal_id, token]
  FrameworkServiceSetting:
    label: Service setting
    table: dd_service_settings
    access: {read: authenticated, write: nobody}
    slots:
      - {name: id, type: integer, autogenerated: true, read_only: true}
      - {name: listener, type: string, required: true, max: 64}
      - {name: setting, type: string, required: true, max: 64}
      - {name: value, type: text}
      - {name: secret, type: boolean, default: false}
      - {name: updated_by, type: integer}
      - {name: updated_at, type: datetime}
    constraints:
      unique: [listener, setting]
`

// frameworkSources appends the framework's classes to an app's model files.
func frameworkSources(files []string) []schema.Source {
	out := make([]schema.Source, 0, len(files)+1)
	for _, f := range files {
		out = append(out, schema.File(f))
	}
	return append(out, schema.String(frameworkModel))
}

// frameworkClass reports whether a class is the framework's own.
func frameworkClass(name string) bool { return strings.HasPrefix(name, "Framework") }

const timeLayout = "2006-01-02 15:04:05"

func (a *App) sessions() *runtime.Handle { return a.Reg.MustClass("FrameworkSession") }
func (a *App) feeds() *runtime.Handle    { return a.Reg.MustClass("FrameworkFeed") }

// sessionFor finds a live session by its token's hash.
func (a *App) sessionFor(ctx context.Context, hash string) (*runtime.Record, bool) {
	s, err := a.sessions().First(ctx, runtime.Query{Where: []runtime.Cond{runtime.Eq("token_hash", hash)}})
	if err != nil {
		return nil, false
	}
	exp := s.String("expires_at")
	if t, err := time.Parse(timeLayout, strings.Replace(exp[:min(len(exp), 19)], "T", " ", 1)); err != nil || time.Now().UTC().After(t) {
		return nil, false
	}
	return s, true
}

// newSession records a session for a principal and returns its token.
func (a *App) newSession(ctx context.Context, principalID int64) (string, error) {
	tok := randomToken()
	s := a.sessions().New(map[string]any{"token_hash": tokenHash(tok), "principal_id": principalID,
		"expires_at": time.Now().UTC().Add(a.cfg.SessionTTL).Format(timeLayout)})
	if err := a.sessions().Save(ctx, s); err != nil {
		return "", err
	}
	// Opportunistic cleanup of expired sessions, and of idle guests (a few at a time).
	old, _ := a.sessions().List(ctx, runtime.Query{Where: []runtime.Cond{{Field: "expires_at", Op: "<", Value: time.Now().UTC().Format(timeLayout)}}, Limit: 20})
	for _, o := range old {
		a.sessions().Delete(ctx, o.ID())
	}
	a.sweepGuests(ctx)
	return tok, nil
}

// dropSessions ends the sessions matching the condition.
func (a *App) dropSessions(ctx context.Context, where runtime.Cond) {
	recs, err := a.sessions().List(ctx, runtime.Query{Where: []runtime.Cond{where}})
	if err != nil {
		return
	}
	for _, r := range recs {
		a.sessions().Delete(ctx, r.ID())
	}
}

// feedToken returns p's feed token, creating one (or a new one when reset).
func (a *App) feedToken(ctx context.Context, principalID int64, reset bool) (string, error) {
	mine := runtime.Query{Where: []runtime.Cond{runtime.Eq("principal_id", principalID)}}
	if !reset {
		if f, err := a.feeds().First(ctx, mine); err == nil {
			return f.String("token"), nil
		} else if !errors.Is(err, runtime.ErrNotFound) {
			return "", err
		}
	}
	if old, err := a.feeds().List(ctx, mine); err == nil {
		for _, o := range old {
			a.feeds().Delete(ctx, o.ID())
		}
	}
	tok := randomToken()
	f := a.feeds().New(map[string]any{"principal_id": principalID, "token": tok})
	return tok, a.feeds().Save(ctx, f)
}

// feedPrincipal finds whose feed a token is.
func (a *App) feedPrincipal(ctx context.Context, tok string) (int64, bool) {
	f, err := a.feeds().First(ctx, runtime.Query{Where: []runtime.Cond{runtime.Eq("token", tok)}})
	if err != nil {
		return 0, false
	}
	return f.Int("principal_id"), true
}
