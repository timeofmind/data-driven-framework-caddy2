package app

import (
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"github.com/timeofmind/data-driven-framework-go/listener"
	"github.com/timeofmind/data-driven-framework-go/listener/llm"
)

// A class routed to an llm listener: saving a record asks the question
// (rendered from the app's template over the record and what it belongs
// to), the providers are tried in order, and the answer is written back
// onto the record through the normal save path — so the model's own
// trigger carries it on (here onto the route the prompt is about).
func TestLLMListener(t *testing.T) {
	if os.Getenv("DDF_TEST_MYSQL_DSN") != "" {
		t.Skip("the routed fixture is SQLite")
	}
	dir := t.TempDir()
	if err := copyDir(fixtureApp, dir); err != nil {
		t.Fatal(err)
	}
	os.WriteFile(filepath.Join(dir, "model", "llm.yaml"), []byte(`
enums:
  AskStatus: {values: [queued, answered, failed], default: queued}
classes:
  Prompt:
    description: "A question about a route"
    access: {owner: member_id, read: owner, write: owner}
    slots:
      - {name: id, type: integer, autogenerated: true, read_only: true}
      - {name: member_id, type: integer, required: true}
      - {name: route_id, type: integer, required: true}
      - {name: status, type: enum, enum: AskStatus, default: queued, read_only: true}
      - {name: response, type: text, read_only: true}
      - {name: response_provider, type: string, read_only: true}
      - {name: response_model, type: string, read_only: true}
      - {name: input_tokens, type: integer, read_only: true}
      - {name: output_tokens, type: integer, read_only: true}
      - {name: answered_at, type: datetime, read_only: true}
      - {name: error, type: text, read_only: true}
    relationships:
      belongs_to:
        - {target: Member, via: member_id, on_delete: cascade}
        - {target: Route, via: route_id, name: route, on_delete: cascade}
    triggers:
      - via: route_id
        if: "self.status == 'answered'"
        set: {name: "self.response"}
`), 0o644)
	os.MkdirAll(filepath.Join(dir, "routing"), 0o755)
	os.WriteFile(filepath.Join(dir, "routing", "walkclub.yaml"), []byte(`
listeners:
  db:   {type: sqlite, dsn: `+filepath.Join(dir, "club.db")+`}
  coach:
    type: llm
    providers: "first, second"
    first_type: claude
    first_model: claude-test
    first_api_key: not-a-key
    second_type: kimi
    second_model: kimi-test
    second_api_key: not-a-key
    max_tokens: 50
    retry_for: 1m
    templates: llm
routes:
  default: {source: db, flows_to: [db]}
  Prompt: {source: db, flows_to: [db, {listener: coach, when: "status == 'queued'", template: name-it}]}
`), 0o644)
	os.MkdirAll(filepath.Join(dir, "llm"), 0o755)
	os.WriteFile(filepath.Join(dir, "llm", "name-it.yaml"), []byte(`
system: "You name walking routes."
prompt: "Name a {{.route.distance_km}} km route for {{.member.name}}."
`), 0o644)
	a, _ := newTestAppAt(t, dir)
	var ll *llm.Listener
	for _, l := range a.Reg.Listeners {
		if x, ok := listener.Unwrap(l).(*llm.Listener); ok {
			ll = x
		}
	}
	if ll == nil {
		t.Fatal("no llm listener")
	}
	var asked []string
	ll.Call = func(ctx context.Context, p *llm.Provider, req *llm.Request) (*llm.Response, error) {
		asked = append(asked, p.Name+": "+req.Prompt)
		if p.Name == "first" {
			return nil, &llm.APIError{Provider: p.Name, Status: 529, Message: "overloaded"}
		}
		if req.System != "You name walking routes." || req.Model != "kimi-test" || req.MaxTokens != 50 {
			t.Errorf("request %+v", req)
		}
		return &llm.Response{Text: "The Long Shore", Model: "kimi-test-1", InputTokens: 9, OutputTokens: 3}, nil
	}
	ctx := context.Background()
	members, routes, prompts := a.Reg.MustClass("Member"), a.Reg.MustClass("Route"), a.Reg.MustClass("Prompt")
	ann := members.New(map[string]any{"email": "ann@example.com", "pw": "longenough1", "name": "Ann"})
	if err := members.Save(ctx, ann); err != nil {
		t.Fatal(err)
	}
	route := routes.New(map[string]any{"member_id": ann.ID(), "name": "Untitled", "distance_km": 4.5})
	if err := routes.Save(ctx, route); err != nil {
		t.Fatal(err)
	}
	p := prompts.New(map[string]any{"member_id": ann.ID(), "route_id": route.ID()})
	if err := prompts.Save(ctx, p); err != nil {
		t.Fatal(err)
	}
	var got map[string]any
	deadline := time.Now().Add(5 * time.Second)
	for time.Now().Before(deadline) {
		rec, err := prompts.Load(ctx, p.ID())
		if err != nil {
			t.Fatal(err)
		}
		if rec.String("status") == "answered" {
			got = rec.Values
			break
		}
		time.Sleep(20 * time.Millisecond)
	}
	if got == nil {
		t.Fatalf("the prompt was not answered; asked %v", asked)
	}
	if got["response"] != "The Long Shore" || got["response_provider"] != "second" || got["response_model"] != "kimi-test-1" || got["input_tokens"] != int64(9) || got["output_tokens"] != int64(3) || got["error"] != nil || got["answered_at"] == nil {
		t.Errorf("recorded %v", got)
	}
	if len(asked) != 2 || !strings.HasSuffix(asked[0], "Name a 4.5 km route for Ann.") || !strings.HasPrefix(asked[1], "second:") {
		t.Errorf("asked %v", asked)
	}
	// The app's trigger carried the answer onto the route.
	r, err := routes.Load(ctx, route.ID())
	if err != nil || r.String("name") != "The Long Shore" {
		t.Errorf("route %v %v", err, r)
	}
	// The write-back was a change like any other: nothing asked again.
	time.Sleep(200 * time.Millisecond)
	if len(asked) != 2 {
		t.Errorf("asked again: %v", asked)
	}
}
