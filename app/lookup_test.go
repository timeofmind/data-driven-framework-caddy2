// A class routed to an http listener: saving a record looks it up at the one
// URL, the answer is mapped onto the record through the normal save path, and
// the API answers the record with its computed values (what a page's script reads).
func TestHTTPLookup(t *testing.T) {
	if os.Getenv("DDF_TEST_MYSQL_DSN") != "" {
		t.Skip("the routed fixture is SQLite")
	}
	api := httptest.NewTLSServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if strings.HasSuffix(r.URL.Path, "/190284") {
			w.Write([]byte(`{"player":{"cfc_id":190284,"name_first":"Ann","name_last":"Lee","regular_rating":1148,"cfc_expiry":"2027-01-31"}}`))
			return
		}
		w.Write([]byte(`{"player":{"cfc_id":-1,"events":[]}}`))
	}))
	defer api.Close()
	dir := t.TempDir()
	if err := copyDir(fixtureApp, dir); err != nil {
		t.Fatal(err)
	}
	os.WriteFile(filepath.Join(dir, "model", "lookup.yaml"), []byte(`
classes:
  CfcLookup:
    access: {owner: member_id, read: owner, write: owner}
    slots:
      - {name: id, type: integer, autogenerated: true, read_only: true}
      - {name: member_id, type: integer, required: true}
      - {name: cfc_id, type: string, required: true, max: 12}
      - {name: first_name, type: string, read_only: true}
      - {name: rating, type: integer, read_only: true}
      - {name: expiry, type: date, read_only: true}
      - {name: lookup_status, type: string, read_only: true}
      - {name: lookup_error, type: text, read_only: true}
      - {name: lookup_looked_up_at, type: datetime, read_only: true}
    computed:
      - {name: note, expr: "if(lookup_status == 'found', 'Found: ' + first_name + ' (' + rating + ')', if(lookup_status == 'not_found', 'Not found', null))"}
    relationships:
      belongs_to:
        - {target: Member, via: member_id, on_delete: cascade}
`), 0o644)
	os.MkdirAll(filepath.Join(dir, "routing"), 0o755)
	os.WriteFile(filepath.Join(dir, "routing", "walkclub.yaml"), []byte(`
listeners:
  db:  {type: sqlite, dsn: `+filepath.Join(dir, "club.db")+`}
  cfc: {type: http, url: "`+api.URL+`/api/player/v1/{cfc_id}", found: "player.name_last != null", map_first_name: player.name_first, map_rating: player.regular_rating, map_expiry: player.cfc_expiry, record_prefix: lookup_}
routes:
  default: {source: db, flows_to: [db]}
  CfcLookup: {source: db, flows_to: [db, {listener: cfc, on: [create, update]}]}
`), 0o644)
	a, srv := newTestAppAt(t, dir)
	for _, l := range a.Reg.Listeners {
		if x, ok := listener.Unwrap(l).(*ddhttp.Listener); ok {
			x.Client = api.Client() // the test server is on 127.0.0.1, which the real client refuses
		}
	}
	b := newBrowser(t, srv)
	b.signup("lookup@example.com", "Lookup")
	resp, err := b.c.Get(srv.URL + "/api/v1/me")
	if err != nil {
		t.Fatal(err)
	}
	var me struct {
		CSRF string `json:"csrf_token"`
	}
	json.NewDecoder(resp.Body).Decode(&me)
	resp.Body.Close()
	do := func(method, path, body string) map[string]any {
		req, _ := http.NewRequest(method, srv.URL+path, strings.NewReader(body))
		req.Header.Set("Content-Type", "application/json")
		req.Header.Set("X-CSRF-Token", me.CSRF)
		resp, err := b.c.Do(req)
		if err != nil {
			t.Fatal(err)
		}
		defer resp.Body.Close()
		var out map[string]any
		json.NewDecoder(resp.Body).Decode(&out)
		return out
	}
	out := do("POST", "/api/v1/cfc-lookups", `{"cfc_id":"190284"}`)
	id, _ := out["id"].(float64)
	if id == 0 {
		t.Fatalf("create: %v", out)
	}
	path := "/api/v1/cfc-lookups/" + itoa(int64(id))
	wait := func(want string) map[string]any {
		deadline := time.Now().Add(5 * time.Second)
		for time.Now().Before(deadline) {
			if out := do("GET", path, ""); out["note"] == want {
				return out
			}
			time.Sleep(20 * time.Millisecond)
		}
		t.Fatalf("never %q: %v", want, do("GET", path, ""))
		return nil
	}
	got := wait("Found: Ann (1148)")
	if got["rating"] != float64(1148) || got["expiry"] != "2027-01-31" || got["lookup_status"] != "found" {
		t.Errorf("looked up: %v", got)
	}
	// a new ID is looked up again; what was learned of the old one is cleared
	do("PATCH", path, `{"cfc_id":"5"}`)
	got = wait("Not found")
	if got["first_name"] != nil || got["rating"] != nil {
		t.Errorf("not found: %v", got)
	}
}
