// Payment Checkout holds the processors (checked with each processor), the
// store's country and the countries it sells to, shipping (none by
// default) and the methods' words; the pay form draws the methods; a payer
// coming back from the processor finishes the payment at /_dd/pay.
func TestPaymentCheckout(t *testing.T) {
	if os.Getenv("DDF_TEST_MYSQL_DSN") != "" {
		t.Skip("the routed fixture is SQLite")
	}
	was := verifyProvider
	verifyProvider = func(ctx context.Context, p payment.Provider) (*payment.Account, error) {
		return &payment.Account{Name: "Walk Club", Country: "US", Currencies: []string{"USD"}, Test: true}, nil
	}
	t.Cleanup(func() { verifyProvider = was })
	dir := checkoutFixture(t)
	a, srv := newServicesApp(t, dir, []byte("a-token-key-shared-by-the-nodes"))
	b := newBrowser(t, srv)
	b.signup("admin@example.com", "Admin")

	code, body, _ := b.get("/admin/checkout")
	if code != http.StatusOK {
		t.Fatalf("Payment Checkout: %d\n%s", code, body)
	}
	for _, want := range []string{`id="processors"`, `id="svc-pay"`, `id="store"`, `id="shipping"`, `id="methods"`, "Test mode:",
		`name="no_shipping" value="1" checked`, `<option value="CA">Canada</option>`, `Set in the app's routing file: CAD.`} {
		if !strings.Contains(body, want) {
			t.Errorf("page lacks %q", want)
		}
	}
	if strings.Contains(body, `name="s_currency"`) || strings.Contains(body, `name="s_brand_name"`) {
		t.Error("the currency and store name are the Store part's, not the processors' card's")
	}
	if !strings.Contains(body, "Choose the store&#39;s country") {
		t.Error("the page asks for the store's country")
	}

	// The pay form, test mode with no processor: one method, nothing charged.
	_, body, _ = b.get("/pay")
	if !strings.Contains(body, `class="dd-pay-method" data-kind="test"`) || !strings.Contains(body, "Test payment") || strings.Contains(body, `id="f-provider"`) {
		t.Fatalf("the payment step in test mode:\n%s", body)
	}

	// The store: in Canada, selling to some countries only — at least one.
	if code, body, _ := b.post("/admin/checkout", url.Values{"op": {"store"}, "country": {"CA"}, "sells_to": {"only"}}); code != http.StatusOK || !strings.Contains(body, "at least one country") {
		t.Fatalf("no country to sell to is refused: %d %s", code, extractAlert(body))
	}
	if code, body, _ := b.post("/admin/checkout", url.Values{"op": {"store"}, "country": {"CA"}, "sells_to": {"only"}, "sell_country": {"CA", "US"}}); code != http.StatusSeeOther {
		t.Fatalf("store: %d %s", code, extractAlert(body))
	}
	if cv := a.checkoutValues(); cv["country"] != "CA" || cv["sells_to"] != "only" || cv["sell_countries"] != "CA,US" {
		t.Fatalf("stored: %v", cv)
	}
	// Shipping on, to Canada only.
	if code, _, _ := b.post("/admin/checkout", url.Values{"op": {"shipping"}, "ship_to": {"only"}, "ship_country": {"CA"}}); code != http.StatusSeeOther {
		t.Fatalf("shipping: %d", code)
	}
	if cv := a.checkoutValues(); cv["ships"] != "1" || cv["ship_countries"] != "CA" {
		t.Fatalf("shipping stored: %v", cv)
	}
	if sv := a.shopValues(); sv["ships"] != true || sv["country"] != "CA" || sv["currency"] != "CAD" {
		t.Fatalf("shop.*: %v", sv)
	}

	// A payment coming back from the processor: approved with its token, and
	// the payer goes on to the payment page; a "to" off this site is not followed.
	member, err := a.Reg.MustClass("Member").First(context.Background(), runtime.Query{Where: []runtime.Cond{runtime.Eq("email", "admin@example.com")}})
	if err != nil {
		t.Fatal(err)
	}
	h := a.Reg.MustClass("Payment")
	pay := h.New(map[string]any{"member_id": member.ID(), "amount_cents": int64(900), "status": "approval_pending", "provider": "paypal"})
	if err := h.Save(context.Background(), pay); err != nil {
		t.Fatal(err)
	}
	id := pay.ID()
	code, _, hdr := b.get("/_dd/pay/payments/" + itoa(id) + "/return?token=TOK-1&PayerID=X&to=https://evil.example/x")
	if code != http.StatusSeeOther || !strings.Contains(hdr.Get("Location"), "/_dd/pay/payments/"+itoa(id)+"?step=return&then=%2F") || strings.Contains(hdr.Get("Location"), "evil") {
		t.Fatalf("return: %d %s", code, hdr.Get("Location"))
	}
	var got *runtime.Record
	for i := 0; i < 50; i++ {
		got, _ = h.Load(context.Background(), id)
		if got != nil && got.String("status") == "captured" {
			break
		}
		time.Sleep(20 * time.Millisecond)
	}
	if got == nil || got.String("approval_token") != "TOK-1" || got.String("status") != "captured" {
		t.Fatalf("the payment after the return (test mode captures): %+v", got)
	}
	code, body, _ = b.get("/_dd/pay/payments/" + itoa(id) + "?step=return&then=/pay")
	if code != http.StatusOK || !strings.Contains(body, `data-dd-pay-page`) || !strings.Contains(body, `data-api="/api/v1/payments/`+itoa(id)+`"`) || !strings.Contains(body, `data-then="/pay"`) {
		t.Fatalf("the payment page: %d\n%s", code, body)
	}
	if code, _, _ := b.get("/_dd/pay/payments/99999"); code != http.StatusNotFound {
		t.Fatalf("an unknown payment: %d", code)
	}

	// Square on, live: its account is checked; a location in USD is refused
	// against the store's CAD.
	if code, body, _ := b.post("/admin/checkout", url.Values{"op": {"service"}, "listener": {"pay"}, "s_mode": {"live"},
		"use_square": {"1"}, "s_square_access_token": {"tok"}, "s_square_location_id": {"L1"}}); code != http.StatusSeeOther {
		t.Fatalf("square: %d %s", code, extractAlert(body))
	}
	if s := a.Reg.Settings("pay"); s["currency"] != "CAD" || s["providers"] != "square" {
		t.Fatalf("saving the card keeps the store's currency: %v", s)
	}
	_, body, _ = b.get("/admin/checkout")
	for _, want := range []string{"✓ Connected to Walk Club (sandbox) · United States · USD", "square&#39;s location takes USD only", "square&#39;s account is in United States, but the store is in Canada", "<strong>Live:</strong>"} {
		if !strings.Contains(body, want) {
			t.Errorf("page lacks %q", want)
		}
	}
	// The methods' words reach the pay form.
	if code, _, _ := b.post("/admin/checkout", url.Values{"op": {"methods"}, "label_square": {"Card"}, "note_square": {"Visa or Mastercard"}, "button": {"Pay"}}); code != http.StatusSeeOther {
		t.Fatalf("methods: %d", code)
	}
	o := a.payOffer("Payment")
	if o == nil || len(o.Methods) != 1 || o.Methods[0].Label != "Card" || o.Methods[0].Note != "Visa or Mastercard" || o.Methods[0].Submit != "Pay" {
		t.Fatalf("the offer: %+v", o)
	}
}

