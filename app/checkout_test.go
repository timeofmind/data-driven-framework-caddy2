// An app selling something gets the framework's orders: a ticket made goes
// in the cart, the order page checks it out and pays it (test mode), and
// the ticket is told it is paid.
func TestSoldThroughTheServer(t *testing.T) {
	if os.Getenv("DDF_TEST_MYSQL_DSN") != "" {
		t.Skip("the routed fixture is SQLite")
	}
	dir := servicesFixture(t, true)
	os.WriteFile(filepath.Join(dir, "model", "tickets.yaml"), []byte(`
classes:
  Ticket:
    access: {owner: member_id, read: owner, write: owner}
    slots:
      - {name: id, type: integer, autogenerated: true, read_only: true}
      - {name: member_id, type: integer, required: true}
      - {name: name, type: string, required: true}
      - {name: order_status, type: string, max: 20}
    sold: {price: "1250", description: "'Ticket for ' + name"}
`), 0o644)
	os.WriteFile(filepath.Join(dir, "pages", "zz-ticket.yaml"), []byte(`
path: /tickets/new
title: A ticket
access: signed_in
interface_views:
  - {type: form, name: buy, creates: Ticket, fields: [name], submit: Add to cart, then: {page: shop-cart}}
`), 0o644)
	a, srv := newServicesApp(t, dir, []byte("a-token-key-shared-by-the-nodes"))
	b := newBrowser(t, srv)
	b.signup("admin@example.com", "Admin")
	if code, body, loc := b.post("/tickets/new", url.Values{"name": {"Ann"}}); code != http.StatusSeeOther || !strings.HasSuffix(loc, "/cart") {
		t.Fatalf("buy: %d %s %s", code, loc, extractAlert(body))
	}
	code, body, _ := b.get("/cart")
	if code != http.StatusOK || !strings.Contains(body, "/orders/") {
		t.Fatalf("the cart: %d\n%s", code, body)
	}
	orders := a.Reg.MustClass("ShopOrder")
	o, err := orders.First(context.Background(), runtime.Query{})
	if err != nil || o.Int("total_cents") != 1250 {
		t.Fatalf("the order: %+v %v", o, err)
	}
	op := "/orders/" + itoa(o.ID())
	code, body, _ = b.get(op)
	if code != http.StatusOK || !strings.Contains(body, "Ticket for Ann") || !strings.Contains(body, "Continue to payment") {
		t.Fatalf("the order page: %d\n%s", code, body)
	}
	if code, body, _ := b.post(op, url.Values{"_view": {"checkout"}, "email": {"admin@example.com"}, "bill_name": {"Admin"}}); code != http.StatusSeeOther {
		t.Fatalf("checkout: %d %s", code, extractAlert(body))
	}
	_, body, _ = b.get(op)
	if !strings.Contains(body, `class="dd-pay-method" data-kind="test"`) {
		t.Fatalf("the payment step on the order:\n%s", body)
	}
	code, body, loc := b.post(op, url.Values{"_view": {"pay"}})
	if code != http.StatusSeeOther || !strings.Contains(loc, "/_dd/pay/dd-shop-payments/") {
		t.Fatalf("pay: %d %s %s", code, loc, extractAlert(body))
	}
	for i := 0; i < 50; i++ {
		if o, _ = orders.Load(context.Background(), o.ID()); o.String("status") == "paid" {
			break
		}
		time.Sleep(20 * time.Millisecond)
	}
	if o.String("status") != "paid" || !o.Bool("payment_test") {
		t.Fatalf("paid in test mode: %v", o.Values)
	}
	tk, _ := a.Reg.MustClass("Ticket").First(context.Background(), runtime.Query{})
	if tk == nil || tk.String("order_status") != "paid" {
		t.Fatalf("the ticket is told: %+v", tk)
	}
}

// Offline ways to pay: an e-Transfer chosen at checkout waits, with the
// store's instructions on the order, until an admin marks it received. The
// customer can't mark their own payment paid — not through the API, and not
// by faking a processor's return.
func TestOfflinePayment(t *testing.T) {
	if os.Getenv("DDF_TEST_MYSQL_DSN") != "" {
		t.Skip("the routed fixture is SQLite")
	}
	dir := servicesFixture(t, true)
	os.WriteFile(filepath.Join(dir, "model", "tickets.yaml"), []byte(`
classes:
  Ticket:
    access: {owner: member_id, read: owner, write: owner}
    slots:
      - {name: id, type: integer, autogenerated: true, read_only: true}
      - {name: member_id, type: integer, required: true}
      - {name: name, type: string, required: true}
    sold: {price: "2000", description: "'Ticket for ' + name"}
`), 0o644)
	os.WriteFile(filepath.Join(dir, "pages", "zz-ticket.yaml"), []byte(`
path: /tickets/new
title: A ticket
access: signed_in
interface_views:
  - {type: form, name: buy, creates: Ticket, fields: [name], submit: Add to cart, then: {page: shop-cart}}
`), 0o644)
	a, srv := newServicesApp(t, dir, []byte("a-token-key-shared-by-the-nodes"))
	admin := newBrowser(t, srv)
	admin.signup("admin@example.com", "Admin")
	if code, body, _ := admin.post("/admin/checkout", url.Values{"op": {"offline"}, "offline_etransfer": {"1"}}); code != http.StatusOK || !strings.Contains(body, "give the email") {
		t.Fatalf("an e-Transfer needs where it goes: %d %s", code, extractAlert(body))
	}
	if code, body, _ := admin.post("/admin/checkout", url.Values{"op": {"offline"}, "offline_etransfer": {"1"}, "etransfer_to": {"pay@club.example"}, "offline_in_person": {"1"}, "in_person_note": {"At the door."}}); code != http.StatusSeeOther {
		t.Fatalf("offline methods: %d %s", code, extractAlert(body))
	}

	ann := newBrowser(t, srv)
	ann.signup("ann@example.com", "Ann")
	ann.post("/tickets/new", url.Values{"name": {"Ann"}})
	ctx := context.Background()
	o, err := a.Reg.MustClass("ShopOrder").First(ctx, runtime.Query{})
	if err != nil {
		t.Fatal(err)
	}
	op := "/orders/" + itoa(o.ID())
	if code, body, _ := ann.post(op, url.Values{"_view": {"checkout"}, "email": {"ann@example.com"}}); code != http.StatusSeeOther {
		t.Fatalf("checkout: %d %s", code, extractAlert(body))
	}
	_, body, _ := ann.get(op)
	for _, want := range []string{`value="offline_etransfer"`, "Interac e-Transfer", `value="offline_in_person"`, "Place order — pay by e-Transfer"} {
		if !strings.Contains(body, want) {
			t.Errorf("the payment step lacks %q", want)
		}
	}
	if strings.Contains(body, `data-kind="test"`) {
		t.Error("with offline methods on, no stand-in test method")
	}
	if code, body, _ := ann.post(op, url.Values{"_view": {"pay"}, "provider": {"offline_etransfer"}}); code != http.StatusSeeOther {
		t.Fatalf("pay by e-Transfer: %d %s", code, extractAlert(body))
	}
	pays := a.Reg.MustClass("ShopPayment")
	var pay *runtime.Record
	for i := 0; i < 50; i++ {
		if pay, _ = pays.First(ctx, runtime.Query{}); pay != nil && pay.String("status") == "approval_pending" {
			break
		}
		time.Sleep(20 * time.Millisecond)
	}
	if pay == nil || pay.String("status") != "approval_pending" || pay.String("provider") != "offline_etransfer" || pay.Int("amount_cents") != 2000 {
		t.Fatalf("an e-Transfer waits: %+v", pay)
	}
	_, body, _ = ann.get(op)
	if !strings.Contains(body, "Send your Interac e-Transfer") || !strings.Contains(body, "pay@club.example") || strings.Contains(body, `name="_view" value="pay"`) {
		t.Fatalf("the order says how to pay, and offers no second payment:\n%s", body)
	}

	// The customer can't mark it paid: not through the API …
	resp, _ := ann.c.Get(srv.URL + "/api/v1/me")
	var me struct {
		CSRF string `json:"csrf_token"`
	}
	json.NewDecoder(resp.Body).Decode(&me)
	resp.Body.Close()
	pid := itoa(pay.ID())
	for _, body := range []string{`{"status":"captured"}`, `{"status":"approved"}`, `{"amount_cents":1}`} {
		req, _ := http.NewRequest("PATCH", srv.URL+"/api/v1/dd-shop-payments/"+pid, strings.NewReader(body))
		req.Header.Set("Content-Type", "application/json")
		req.Header.Set("X-CSRF-Token", me.CSRF)
		if r, err := ann.c.Do(req); err == nil {
			r.Body.Close()
		}
	}
	// … nor by coming back as if from a processor.
	ann.get("/_dd/pay/dd-shop-payments/" + pid + "/return?token=FAKE")
	time.Sleep(100 * time.Millisecond)
	if pay, _ = pays.Load(ctx, pay.ID()); pay.String("status") != "approval_pending" || pay.Int("amount_cents") != 2000 {
		t.Fatalf("the customer moved their own payment: %v", pay.Values)
	}
	if o, _ = a.Reg.MustClass("ShopOrder").Load(ctx, o.ID()); o.String("status") == "paid" {
		t.Fatal("the order was marked paid by its customer")
	}

	// The admin marks it received: captured, and the order is paid.
	if code, body, _ := admin.post("/admin/shop-payments/"+pid, url.Values{"_view": {"received"}}); code != http.StatusSeeOther {
		t.Fatalf("mark received: %d %s", code, extractAlert(body))
	}
	for i := 0; i < 50; i++ {
		if o, _ = a.Reg.MustClass("ShopOrder").Load(ctx, o.ID()); o.String("status") == "paid" {
			break
		}
		time.Sleep(20 * time.Millisecond)
	}
	if o.String("status") != "paid" || o.String("paid_via") != "offline_etransfer" || o.Bool("payment_test") {
		t.Fatalf("paid by e-Transfer: %v", o.Values)
	}
}

// A processor's webhook: no session and no CSRF token; one addressed to no
// payment listener and provider in use (or the app has no https address the
// processors could call, as here) is not found, and a GET is not taken.
func TestPayHook(t *testing.T) {
	if os.Getenv("DDF_TEST_MYSQL_DSN") != "" {
		t.Skip("the routed fixture is SQLite")
	}
	_, srv := newServicesApp(t, servicesFixture(t, true), []byte("a-token-key-shared-by-the-nodes"))
	for _, c := range []struct{ method, path string }{
		{"POST", "/_dd/pay/hook/pay/paypal"},  // test mode, http: no webhooks
		{"POST", "/_dd/pay/hook/nope/paypal"}, // no such listener
		{"POST", "/_dd/pay/hook/pay"},         // no provider
		{"GET", "/_dd/pay/hook/pay/paypal"},
	} {
		req, _ := http.NewRequest(c.method, srv.URL+c.path, strings.NewReader(`{"resource":{"id":"O-1"}}`))
		resp, err := http.DefaultClient.Do(req)
		if err != nil {
			t.Fatal(err)
		}
		resp.Body.Close()
		if resp.StatusCode != http.StatusNotFound {
			t.Errorf("%s %s: %d", c.method, c.path, resp.StatusCode)
		}
	}
}
